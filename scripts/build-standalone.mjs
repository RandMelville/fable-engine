// Bundles src/standalone.ts into a minified IIFE string and writes it to
// src/generated/standaloneBundle.ts, so export.ts can inline the player runtime
// into the self-contained HTML.

import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const result = await build({
  entryPoints: [resolve(root, "src/standalone.ts")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2020",
  write: false,
});

const code = result.outputFiles[0].text;
const out = `// Generated by scripts/build-standalone.mjs — do not edit by hand.
export const standaloneBundle = ${JSON.stringify(code)};
`;

writeFileSync(resolve(root, "src/generated/standaloneBundle.ts"), out);
console.log(`build:standalone -> ${code.length} bytes bundled`);
